// Phase 8 W5.A.1 — wage role rows proxy write routes.
//
// Two operator-scoped routes — the operator's own wage mix only.
// Idempotency-Key required on both. Pattern mirrors the W2.B
// notification preferences seam (in-memory replay cache, plain-English
// rejection envelope, JWT-resolved operator/location, no client-side
// UUID generation).
//
//   POST   /v1/operator/wage-role-rows
//   DELETE /v1/operator/wage-role-rows/:wage_role_row_id
//
// Auth:
//   * Bearer token resolves to OperatorContext (operatorId required).
//   * Caller must hold an operator-write role (`operator_owner`);
//     the dispatcher in advisor_proxy.dart checks
//     `kOperatorWriteRoles` before delegating here.
//   * RLS on the table is the backup defense; the repository pattern
//     SET LOCALs the operator + location every transaction.
//
// Idempotency:
//   * Idempotency-Key required on POST and DELETE; missing / blank /
//     >200 chars → 400 idempotency_key_missing /
//     idempotency_key_too_long.
//   * Same key + same body within TTL → replay (cached response).
//   * Same key + different body → 409 idempotency_key_conflict.
//
// Audit:
//   * On every successful write the router fires a single audit row
//     through [WageRoleRowsAuditSink]. Production wires
//     [ProductionWageRoleRowsAuditSink] which lands one
//     `public.audit_logs` row per write (hash-chained, operator-scoped,
//     wrapped in the tenant tx). A replayed idempotent request does NOT
//     fire a new audit row because the router replays the cached
//     response without re-invoking the gateway.
//
// CLAUDE.md compliance:
//   * Operator-scoped — operator_id resolved from JWT, never from URL.
//   * No client-side UUIDs — id is server-generated by gen_random_uuid().
//   * Plain-English error messages, no engineering jargon.
//   * Permissions + audit (Hard Contract 7) — every write is permission
//     checked, idempotency keyed, and audit logged.

import 'dart:convert';

