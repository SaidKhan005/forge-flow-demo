/// Router. Caller resolves auth + JWT scope, then hands off here.
class WageRoleRowsRouter {
  WageRoleRowsRouter({
    required this.gateway,
    WageRoleRowsIdempotencyCache? idempotencyCache,
    WageRoleRowsAuditSink? auditSink,
    DateTime Function()? now,
  }) : _idempotencyCache = idempotencyCache ?? WageRoleRowsIdempotencyCache(),
       _auditSink = auditSink ?? const NoopWageRoleRowsAuditSink(),
       _now = now ?? DateTime.now;

  final WageRoleRowsGateway gateway;
  final WageRoleRowsIdempotencyCache _idempotencyCache;
  final WageRoleRowsAuditSink _auditSink;
  final DateTime Function() _now;

  /// True when [path] / [method] is one of the two routes.
  static bool matches(String path, String method) {
    if (method == 'POST' && path == wageRoleRowsPath) return true;
    if (method == 'DELETE' && path.startsWith(wageRoleRowsPrefix)) return true;
    return false;
  }

  /// Handle one request once auth + scope resolution + the
  /// Idempotency-Key header have been read by the caller.
  ///
  /// [actorKind] feeds the audit-log row (`'user'` for end-users,
  /// `'service'` for service-principal-issued JWTs); the dispatcher in
  /// `advisor_proxy.dart` reads this from the resolved JWT scope.
  Future<({int statusCode, Map<String, Object?> body})> handle({
    required String method,
    required String path,
    required String operatorId,
    required String locationId,
    required String? actorUserId,
    required String idempotencyKey,
    String actorKind = 'user',
    Map<String, Object?>? body,
  }) async {
    try {
      if (method == 'POST' && path == wageRoleRowsPath) {
        return await _runIdempotent(
          operatorId: operatorId,
          locationId: locationId,
          route: 'POST $path',
          idempotencyKey: idempotencyKey,
          body: body ?? const <String, Object?>{},
          compute: () => _handleUpsert(
            operatorId: operatorId,
            locationId: locationId,
            actorUserId: actorUserId,
            actorKind: actorKind,
            body: body ?? const <String, Object?>{},
          ),
        );
      }
      if (method == 'DELETE' && path.startsWith(wageRoleRowsPrefix)) {
        final suffix = path.substring(wageRoleRowsPrefix.length);
        if (suffix.isEmpty || suffix.contains('/')) {
          return (
            statusCode: 404,
            body: const <String, Object?>{
              'error': 'not_found',
              'message': 'route not found',
            },
          );
        }
        final wageRoleRowId = Uri.decodeComponent(suffix).toLowerCase();
        if (!_kUuidPattern.hasMatch(wageRoleRowId)) {
          throw const WageRoleRowsRouteRejected(
            code: 'invalid_wage_role_row_id',
            message: 'wage_role_row_id must be a UUID',
            statusCode: 400,
          );
        }
        return await _runIdempotent(
          operatorId: operatorId,
          locationId: locationId,
          route: 'DELETE $path',
          idempotencyKey: idempotencyKey,
          body: const <String, Object?>{},
          compute: () => _handleSoftDelete(
            operatorId: operatorId,
            locationId: locationId,
            wageRoleRowId: wageRoleRowId,
            actorUserId: actorUserId,
            actorKind: actorKind,
          ),
        );
      }
      return (
        statusCode: 404,
        body: const <String, Object?>{
          'error': 'not_found',
          'message': 'route not found',
        },
      );
    } on WageRoleRowsRouteRejected catch (rejected) {
      return (
        statusCode: rejected.statusCode,
        body: <String, Object?>{
          'error': rejected.code,
          'message': rejected.message,
          ...rejected.extras,
        },
      );
    }
  }

  Future<({int statusCode, Map<String, Object?> body})> _runIdempotent({
    required String operatorId,
    required String locationId,
    required String route,
    required String idempotencyKey,
    required Map<String, Object?> body,
    required Future<({int statusCode, Map<String, Object?> body})> Function()
    compute,
  }) {
    final bodyHash = hashWageRoleRowsRequest(body);
    return _idempotencyCache.runOrReplay(
      operatorId: operatorId,
      locationId: locationId,
      route: route,
      idempotencyKey: idempotencyKey,
      requestBodyHash: bodyHash,
      compute: compute,
    );
  }

  Future<({int statusCode, Map<String, Object?> body})> _handleUpsert({
    required String operatorId,
    required String locationId,
    required String? actorUserId,
    required String actorKind,
    required Map<String, Object?> body,
  }) async {
    final restaurantId = _requireString(body, 'restaurant_id', maxLength: 128);
    final roleName = _requireString(body, 'role_name', maxLength: 128);
    if (roleName != roleName.trim()) {
      throw const WageRoleRowsRouteRejected(
        code: 'invalid_role_name',
        message: 'role_name must not have leading or trailing whitespace',
        statusCode: 400,
      );
    }
    final laborBucket = _requireString(body, 'labor_bucket', maxLength: 16);
    if (!_kAdmittedLaborBuckets.contains(laborBucket)) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_labor_bucket',
        message:
            'labor_bucket must be one of ${_kAdmittedLaborBuckets.join(' / ')}',
        statusCode: 400,
      );
    }
    final hourlyRate = _requireRate(body, 'hourly_rate');
    final weightedHours = _requireRate(body, 'weighted_hours');

    final jobCode = _optionalString(body, 'job_code', maxLength: 128);
    final vendorId = _optionalString(body, 'vendor_id', maxLength: 64);
    final vendorRoleId = _optionalString(
      body,
      'vendor_role_id',
      maxLength: 128,
    );

    final sourceWire = body['source'];
    WageRoleRowSource source = WageRoleRowSource.operatorManual;
    if (sourceWire != null) {
      if (sourceWire is! String || !_kAdmittedSources.contains(sourceWire)) {
        throw WageRoleRowsRouteRejected(
          code: 'invalid_source',
          message: 'source must be one of ${_kAdmittedSources.join(' / ')}',
          statusCode: 400,
        );
      }
      source = WageRoleRowSourceWire.fromWire(sourceWire);
    }

    final metadataRaw = body['metadata'];
    Map<String, Object?> metadata = const <String, Object?>{};
    if (metadataRaw != null) {
      if (metadataRaw is! Map) {
        throw const WageRoleRowsRouteRejected(
          code: 'invalid_metadata',
          message: 'metadata must be a JSON object',
          statusCode: 400,
        );
      }
      metadata = Map<String, Object?>.from(metadataRaw);
    }

    final record = await gateway.upsert(
      operatorId: operatorId,
      locationId: locationId,
      restaurantId: restaurantId,
      roleName: roleName,
      laborBucket: laborBucket,
      hourlyRate: hourlyRate,
      weightedHours: weightedHours,
      jobCode: jobCode,
      vendorId: vendorId,
      vendorRoleId: vendorRoleId,
      source: source,
      metadata: metadata,
      actorUserId: actorUserId,
    );
    // Hash-chained audit log (Hard Contract 7). The sink swallows
    // failures so a downstream observability outage cannot 5xx a
    // request whose business write already committed.
    await _auditSink.recordUpsert(
      operatorId: operatorId,
      locationId: locationId,
      actorUserId: actorUserId ?? '',
      actorKind: actorKind,
      wageRoleRowId: record.wageRoleRowId,
      restaurantId: record.restaurantId,
      roleName: record.roleName,
      laborBucket: record.laborBucket,
      hourlyRate: record.hourlyRate,
      weightedHours: record.weightedHours,
      source: record.source.wire,
      occurredAt: _now().toUtc(),
    );
    return (statusCode: 200, body: record.toJson());
  }

  Future<({int statusCode, Map<String, Object?> body})> _handleSoftDelete({
    required String operatorId,
    required String locationId,
    required String wageRoleRowId,
    required String? actorUserId,
    required String actorKind,
  }) async {
    final removed = await gateway.softDelete(
      operatorId: operatorId,
      locationId: locationId,
      wageRoleRowId: wageRoleRowId,
      actorUserId: actorUserId,
    );
    // Hash-chained audit log even when the row was already inactive
    // (`removed = false`), so a delete attempt is always recorded.
    await _auditSink.recordSoftDelete(
      operatorId: operatorId,
      locationId: locationId,
      actorUserId: actorUserId ?? '',
      actorKind: actorKind,
      wageRoleRowId: wageRoleRowId,
      removed: removed,
      occurredAt: _now().toUtc(),
    );
    return (
      statusCode: 200,
      body: <String, Object?>{
        'wage_role_row_id': wageRoleRowId,
        'removed': removed,
      },
    );
  }

  /// Read a required string field from [body], rejecting missing /
  /// blank / oversized values with a typed 400.
  String _requireString(
    Map<String, Object?> body,
    String field, {
    required int maxLength,
  }) {
    final raw = body[field];
    if (raw is! String) {
      throw WageRoleRowsRouteRejected(
        code: 'missing_$field',
        message: '$field is required',
        statusCode: 400,
      );
    }
    final value = raw.trim();
    if (value.isEmpty) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must not be blank',
        statusCode: 400,
      );
    }
    if (value.length > maxLength) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must be $maxLength characters or fewer',
        statusCode: 400,
      );
    }
    return value;
  }

  /// Read an optional string field from [body]; null / absent / blank
  /// → null. Oversized values throw.
  String? _optionalString(
    Map<String, Object?> body,
    String field, {
    required int maxLength,
  }) {
    final raw = body[field];
    if (raw == null) return null;
    if (raw is! String) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must be a string when present',
        statusCode: 400,
      );
    }
    final value = raw.trim();
    if (value.isEmpty) return null;
    if (value.length > maxLength) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must be $maxLength characters or fewer',
        statusCode: 400,
      );
    }
    return value;
  }

  /// Read a numeric rate field (hourly_rate, weighted_hours) and
  /// reject negative / out-of-range values.
  double _requireRate(Map<String, Object?> body, String field) {
    final raw = body[field];
    double? value;
    if (raw is num) {
      value = raw.toDouble();
    } else if (raw is String) {
      value = double.tryParse(raw);
    }
    if (value == null) {
      throw WageRoleRowsRouteRejected(
        code: 'missing_$field',
        message: '$field is required and must be numeric',
        statusCode: 400,
      );
    }
    if (value.isNaN || value.isInfinite) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must be a finite number',
        statusCode: 400,
      );
    }
    if (value < 0 || value > 10000) {
      throw WageRoleRowsRouteRejected(
        code: 'invalid_$field',
        message: '$field must be between 0 and 10000',
        statusCode: 400,
      );
    }
    return value;
  }
}
