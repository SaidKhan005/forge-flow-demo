/// Route prefix.
const String wageRoleRowsPath = '/v1/operator/wage-role-rows';
const String wageRoleRowsPrefix = '$wageRoleRowsPath/';

/// Labor-bucket values admitted by the migration's CHECK constraint.
const Set<String> _kAdmittedLaborBuckets = <String>{'foh', 'boh', 'manager'};

/// Source values admitted by the migration's CHECK constraint.
const Set<String> _kAdmittedSources = <String>{
  'operator_manual',
  'vendor_per_position',
  'admin_seed',
  'migration_seed',
};

/// Strict 8-4-4-4-12 lowercase UUID format. The repository's
/// TenantContext also validates, but failing earlier in the route
/// keeps the 400 envelope consistent with the rest of the surface.
final RegExp _kUuidPattern = RegExp(
  r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
);

/// Lightweight rejection envelope — same shape as
/// `OperatorWriteRejected` / `NotificationPreferenceRouteRejected`.
class WageRoleRowsRouteRejected implements Exception {
  const WageRoleRowsRouteRejected({
    required this.code,
    required this.message,
    required this.statusCode,
    this.extras = const <String, Object?>{},
  });

  final String code;
  final String message;
  final int statusCode;
  final Map<String, Object?> extras;
}

