/// In-memory replay cache for POST / DELETE routes. Mirrors
/// `NotificationPreferencesIdempotencyCache` shape but local to this
/// surface so the existing operator-write cache stays scoped to its
/// routes.
class WageRoleRowsIdempotencyCache {
  WageRoleRowsIdempotencyCache({
    this.ttl = const Duration(hours: 1),
    this.maxEntries = 5000,
    DateTime Function()? now,
  }) : _now = now ?? DateTime.now;

  final Duration ttl;
  final int maxEntries;
  final DateTime Function() _now;

  final Map<String, _CacheEntry> _store = <String, _CacheEntry>{};

  Future<({int statusCode, Map<String, Object?> body})> runOrReplay({
    required String operatorId,
    required String locationId,
    required String route,
    required String idempotencyKey,
    required String requestBodyHash,
    required Future<({int statusCode, Map<String, Object?> body})> Function()
    compute,
  }) async {
    _gc();
    final key = '$operatorId|$locationId|$route|$idempotencyKey';
    final cached = _store[key];
    if (cached != null) {
      if (cached.bodyHash != requestBodyHash) {
        throw const WageRoleRowsRouteRejected(
          code: 'idempotency_key_conflict',
          message: 'Idempotency-Key was reused with a different body',
          statusCode: 409,
        );
      }
      return (statusCode: cached.statusCode, body: cached.body);
    }
    final result = await compute();
    if (result.statusCode >= 200 &&
        result.statusCode < 500 &&
        result.statusCode != 429) {
      _store[key] = _CacheEntry(
        statusCode: result.statusCode,
        body: result.body,
        bodyHash: requestBodyHash,
        expiresAt: _now().add(ttl),
      );
      _evictOverflow();
    }
    return result;
  }

  void _gc() {
    final cutoff = _now();
    _store.removeWhere((_, entry) => entry.expiresAt.isBefore(cutoff));
  }

  void _evictOverflow() {
    while (_store.length > maxEntries) {
      _store.remove(_store.keys.first);
    }
  }
}

class _CacheEntry {
  _CacheEntry({
    required this.statusCode,
    required this.body,
    required this.bodyHash,
    required this.expiresAt,
  });

  final int statusCode;
  final Map<String, Object?> body;
  final String bodyHash;
  final DateTime expiresAt;
}

/// Stable hash of a request payload (canonical JSON, sorted keys) —
/// matches `hashOperatorRequestBody` shape so retries hash to the
/// same value regardless of map insertion order.
String hashWageRoleRowsRequest(Map<String, Object?> body) {
  final canonical = _canonicalJson(body);
  return sha256.convert(utf8.encode(canonical)).toString();
}

String _canonicalJson(Object? value) {
  if (value is Map) {
    final keys = value.keys.map((k) => k.toString()).toList()..sort();
    final entries = <String>[
      for (final k in keys) '${jsonEncode(k)}:${_canonicalJson(value[k])}',
    ];
    return '{${entries.join(',')}}';
  }
  if (value is List) {
    return '[${value.map(_canonicalJson).join(',')}]';
  }
  return jsonEncode(value);
}

/// Audit sink fired once per successful wage-role-rows write. Mirrors
/// the [OperatorWriteAuditSink] shape so production can reuse the same
/// hash-chained `public.audit_logs` writer wired for operator account /
/// business timing writes. The router invokes this AFTER the gateway
/// returns a successful result; replayed idempotent requests do NOT
/// re-fire the sink (the cache short-circuits before `compute` runs).
///
/// Implementations MUST swallow audit failures rather than rethrowing —
/// the business write has already committed by the time this is called
/// and a downstream observability failure must not cause the proxy to
/// return a 5xx for a request whose actual side-effect succeeded.
abstract class WageRoleRowsAuditSink {
  Future<void> recordUpsert({
    required String operatorId,
    required String locationId,
    required String actorUserId,
    required String actorKind,
    required String wageRoleRowId,
    required String restaurantId,
    required String roleName,
    required String laborBucket,
    required double hourlyRate,
    required double weightedHours,
    required String source,
    required DateTime occurredAt,
  });

  Future<void> recordSoftDelete({
    required String operatorId,
    required String locationId,
    required String actorUserId,
    required String actorKind,
    required String wageRoleRowId,
    required bool removed,
    required DateTime occurredAt,
  });
}

