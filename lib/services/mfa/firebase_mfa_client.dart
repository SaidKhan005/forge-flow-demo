// Phase 9 live-closeout B11 - FirebaseMfaClient adapter seam.
//
// Production [MfaEnrollmentService] talks to Firebase Identity
// Platform's MultiFactor API through this adapter rather than
// importing `firebase_auth` directly. Same shape as the B4
// `FirebaseAuthClient` seam — the SDK adapter that imports
// `firebase_auth` lives in a single sibling file and is gated
// behind the iOS/Android wiring (B7).
//
// Hard rules:
//
//   * No file outside `lib/services/mfa/firebase_mfa_client_*.dart`
//     may import the real `package:firebase_auth/firebase_auth.dart`
//     for MFA paths.
//   * The default binding is [ScaffoldFailingFirebaseMfaClient] so
//     a misconfigured deploy surfaces a "no Firebase MFA backend
//     wired" error rather than silently allowing.
//   * TOTP secrets (and the otpauth:// URL that contains them) NEVER
//     appear in `toString()`, debug prints, or error messages from
//     this layer — they leak the MFA factor itself.

/// Begin-enrollment payload returned by Firebase. The application
/// service maps this into the higher-level [TotpEnrollmentSetup] the
/// UI renders.
class FirebaseMfaTotpBeginPayload {
  const FirebaseMfaTotpBeginPayload({
    required this.factorId,
    required this.secretBase32,
    required this.otpAuthUrl,
  });

  /// Firebase MultiFactor session-scoped factor id (NOT the
  /// `mfa_factors.factor_id` UUID — that is generated by the proxy
  /// when the row is inserted).
  final String factorId;

  /// Base32-encoded TOTP secret. Echoed to the user once as a
  /// fallback for QR scanning. Sensitive — never logged.
  final String secretBase32;

  /// `otpauth://` URL the UI renders as a QR code. Embeds the secret;
  /// sensitive — never logged.
  final String otpAuthUrl;
}

/// Outcome of [FirebaseMfaClient.confirmTotpEnrollment].
sealed class FirebaseMfaConfirmOutcome {
  const FirebaseMfaConfirmOutcome();
}

/// Confirmation succeeded. [factorMetadata] is whatever JSON the
/// proxy will persist on the `mfa_factors.factor_metadata` column
/// (e.g. `{"firebase_factor_uid": "abc", "issuer": "Forge & Flow"}`).
class FirebaseMfaConfirmSucceeded extends FirebaseMfaConfirmOutcome {
  const FirebaseMfaConfirmSucceeded({required this.factorMetadata});

  final Map<String, Object?> factorMetadata;
}

/// Confirmation failed (wrong OTP, expired session, etc.). [code] is
/// the stable machine-readable code the UI maps to copy. [message]
/// MUST NOT echo the OTP or the secret.
class FirebaseMfaConfirmFailed extends FirebaseMfaConfirmOutcome {
  const FirebaseMfaConfirmFailed({required this.code, required this.message});

  final String code;
  final String message;
}

class FirebaseMfaTotpFactor {
  const FirebaseMfaTotpFactor({
    required this.factorId,
    required this.enrolledAt,
    this.displayName,
  });

  final String factorId;
  final DateTime enrolledAt;
  final String? displayName;
}

/// What the production [MfaEnrollmentService] needs from a Firebase
/// Auth MultiFactor SDK. Production wires a thin adapter around
/// `MultiFactor.beginEnrollment` + `TotpMultiFactorGenerator`. Tests
/// inject fakes that return canned payloads.
abstract class FirebaseMfaClient {
  /// Begins TOTP enrollment for [userId]. Returns the secret + the
  /// otpauth URL the UI renders as a QR.
  Future<FirebaseMfaTotpBeginPayload> beginTotpEnrollment({
    String authorizationIdToken = '',
    required String userId,
    required String userEmail,
    required String issuerName,
  });

  /// Confirms enrollment by exchanging the first OTP from the user's
  /// authenticator app for a permanent enrolled factor.
  Future<FirebaseMfaConfirmOutcome> confirmTotpEnrollment({
    String authorizationIdToken = '',
    required String factorId,
    required String oneTimeCode,
    String issuerName = 'Forge & Flow',
  });

  /// Lists Firebase-side TOTP factors for the current user. The Settings MFA
  /// screen uses this as a safety net when Firebase has an enrolled factor
  /// before the local `mfa_factors` row is visible.
  Future<List<FirebaseMfaTotpFactor>> listTotpFactors({
    String authorizationIdToken = '',
    required String userId,
  });

  /// Removes a previously enrolled factor (Firebase-side). The
  /// proxy then writes `mfa_factors.revoked_at` for the local row.
  /// Used by the 24-hour-delayed MFA removal flow (`MfaRemovalService`).
  Future<void> unenrollFactor({
    String authorizationIdToken = '',
    required String userId,
    required String factorId,
  });
}

/// Hard-fail-closed default. Every method throws so a production
/// deploy that wires the production [MfaEnrollmentService] but
/// forgets the real SDK adapter surfaces a clear "no Firebase MFA
/// backend wired" error rather than silently rejecting.
class ScaffoldFailingFirebaseMfaClient implements FirebaseMfaClient {
  const ScaffoldFailingFirebaseMfaClient();

  @override
  Future<FirebaseMfaTotpBeginPayload> beginTotpEnrollment({
    String authorizationIdToken = '',
    required String userId,
    required String userEmail,
    required String issuerName,
  }) async {
    throw StateError(_message);
  }

  @override
  Future<FirebaseMfaConfirmOutcome> confirmTotpEnrollment({
    String authorizationIdToken = '',
    required String factorId,
    required String oneTimeCode,
    String issuerName = 'Forge & Flow',
  }) async {
    throw StateError(_message);
  }

  @override
  Future<List<FirebaseMfaTotpFactor>> listTotpFactors({
    String authorizationIdToken = '',
    required String userId,
  }) async {
    throw StateError(_message);
  }

  @override
  Future<void> unenrollFactor({
    String authorizationIdToken = '',
    required String userId,
    required String factorId,
  }) async {
    throw StateError(_message);
  }

  static const String _message =
      'B11 scaffold: real FirebaseMfaClient is not wired — bind the '
      '`firebase_auth` MultiFactor adapter (TotpMultiFactorGenerator, '
      'MultiFactor.beginEnrollment) in the proxy bootstrap before '
      'exposing the MFA enrollment surface.';
}
