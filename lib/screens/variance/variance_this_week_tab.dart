/// Variance "This Week" content. Renders the Whole Week variance
/// table (WTD vs Plan + Dollar Impact + Primary Driver + Full Week
/// Projection). The earlier `Whole Week | Daypart` toggle was cut V1
/// per operator decision 2026-05-15: the daypart branch only showed
/// raw per-period actuals (no target column, no variance math), which
/// duplicated the Shift daypart view and confused operators. Shift's
/// daypart cards remain the per-period surface; Variance speaks
/// week-level variance only.
class _ThisWeekContent extends StatelessWidget {
  final WeekData weekData;
  const _ThisWeekContent({required this.weekData});

  static String _formatMonthDay(String isoDate) {
    const months = [
      'Jan',
      'Feb',
      'Mar',
      'Apr',
      'May',
      'Jun',
      'Jul',
      'Aug',
      'Sep',
      'Oct',
      'Nov',
      'Dec',
    ];
    final parts = isoDate.split('-');
    if (parts.length != 3) return isoDate;
    final month = int.tryParse(parts[1]);
    final day = int.tryParse(parts[2]);
    if (month == null || day == null || month < 1 || month > 12) {
      return isoDate;
    }
    return '${months[month - 1]} $day';
  }

  @override
  Widget build(BuildContext context) {
    // 7.58.UX.5 (F-1): explicit lookup; null → on_model / unknown id, render
    // the degraded `LeverCardNotYetAvailable` instead of silently falling
    // through to coversDown. See phase_7_58_primary_driver_contract.md.
    final lever = LeverCards.lookup(weekData.primaryLeverId);
    // 7.58.UX.1: per-axis dollar attribution. Wages come from the same
    // active target profile that built `weekData`; FOH/BOH blended actuals
    // are derived from `storedTotalFohLaborDollar` / `storedTotalBohLaborDollar`
    // when both are present. When the profile is unavailable (legacy widget
    // tests) the attribution map is null and the card renders unchanged.
    final activeProfile =
        context.watch<ActiveTargetProfileNotifier?>()?.profile;
    Map<String, double>? primaryDriverDollarImpactByAxis;
    if (lever != null && activeProfile != null) {
      final fohDollars = weekData.storedTotalFohLaborDollar;
      final bohDollars = weekData.storedTotalBohLaborDollar;
      primaryDriverDollarImpactByAxis = LaborModel.attributeDollarImpactByAxis(
        actualCovers: weekData.totalCovers,
        forecastCovers: weekData.wtdForecastCovers,
        actualFohHours: weekData.totalFohHours,
        actualBohHours: weekData.totalBohHours,
        avgPPA: weekData.avgPPA,
        targetCPLH: weekData.targetCPLH,
        targetSPLH: weekData.targetSPLH,
        targetPPA: weekData.targetPPA,
        targetFohWage: activeProfile.fohWage,
        targetBohWage: activeProfile.bohWage,
        avgCPLH: weekData.avgCPLH,
        avgSPLH: weekData.avgSPLH,
        avgFohBlendedWage: (fohDollars != null && weekData.totalFohHours > 0)
            ? fohDollars / weekData.totalFohHours
            : null,
        avgBohBlendedWage: (bohDollars != null && weekData.totalBohHours > 0)
            ? bohDollars / weekData.totalBohHours
            : null,
      );
    }

    return CustomScrollView(
      // Build all slivers eagerly so section labels below the fold are
      // available to widget tests and scroll-to-find helpers. The page
      // has at most ~4 sections — no performance concern.
      cacheExtent: 9999,
      slivers: [
        // Sub-header — same padding as Previous Weeks and Learn so
        // the three tab sub-headers align vertically.
        SliverToBoxAdapter(
          child: Padding(
            padding: const EdgeInsets.fromLTRB(16, 16, 16, 4),
            child: Text('This Week', style: AppTextStyles.display28()),
          ),
        ),
        SliverToBoxAdapter(
          child: Padding(
            padding: const EdgeInsets.fromLTRB(16, 0, 16, 8),
            child: Text(
              weekData.lastClosedBusinessDate != null
                  ? '${_formatMonthDay(weekData.lastClosedBusinessDate!)} \u00b7 ${weekData.lastClosedDay} \u00b7 Business Day ${weekData.closedDayNumber} of 7'
                  : '${weekData.weekLabel} \u00b7 ${weekData.lastClosedDay} \u00b7 Business Day ${weekData.closedDayNumber} of 7',
              style: AppTextStyles.body13(color: AppColors.textMuted),
            ),
          ),
        ),

        // The earlier `Whole Week | Daypart` scope toggle was cut V1
        // (operator decision 2026-05-15). Variance now renders only
        // the whole-week truth — the daypart lens shipped no variance
        // math (raw actuals only) and duplicated Shift's daypart
        // cards. Shift remains the per-period surface.

        // WTD Variance Table
        SliverMainAxisGroup(
          slivers: [
            SliverPersistentHeader(
              pinned: true,
              delegate: StickySectionDelegate('WEEK-TO-DATE vs PLAN'),
            ),
            SliverPersistentHeader(
              pinned: true,
              delegate: const StickyColumnHeaderDelegate(),
            ),
            SliverToBoxAdapter(child: _WtdTable(data: weekData)),
            const SliverToBoxAdapter(child: SizedBox(height: 24)),
          ],
        ),

        // Dollar Impact Card
        SliverMainAxisGroup(
          slivers: [
            SliverPersistentHeader(
              pinned: true,
              delegate: StickySectionDelegate('DOLLAR IMPACT'),
            ),
            SliverToBoxAdapter(
              child: DollarImpactCard(
                weekImpact: weekData.dollarGap,
                monthImpact: weekData.monthDollarImpact,
                sixtyDayImpact: weekData.sixtyDayDollarImpact,
                annualizedImpact: weekData.annualizedDollarImpact,
                footerText: 'Through ${weekData.lastClosedDay}',
                theoreticalLaborPct: weekData.theoreticalLaborPct,
                actualLaborPct: weekData.actualLaborPct,
              ),
            ),
            const SliverToBoxAdapter(child: SizedBox(height: 24)),
          ],
        ),

        // Primary Lever
        SliverMainAxisGroup(
          slivers: [
            SliverPersistentHeader(
              pinned: true,
              delegate: StickySectionDelegate('PRIMARY DRIVER'),
            ),
            SliverToBoxAdapter(
              child: lever == null
                  ? const LeverCardNotYetAvailable()
                  : LeverCardWidget(
                      data: lever,
                      dollarImpactByAxis:
                          primaryDriverDollarImpactByAxis,
                      // 7.58.UX.8 — OPZ-aware row annotation. CPLH ceiling
                      // comes from the active target profile; SPLH ceiling
                      // is not modeled in `ActiveTargetProfile` today, so
                      // the splh annotation stays gated on null. When the
                      // notifier is out of scope (legacy widget tests),
                      // both actual + ceiling read null and the row
                      // renders unchanged.
                      actualCPLH: activeProfile != null
                          ? weekData.avgCPLH
                          : null,
                      opzCeilingCPLH: activeProfile?.opzCeilingCPLH,
                      actualSPLH: null,
                      opzCeilingSPLH: null,
                    ),
            ),
            const SliverToBoxAdapter(child: SizedBox(height: 24)),
          ],
        ),

        // Full Week Projection
        SliverMainAxisGroup(
          slivers: [
            SliverPersistentHeader(
              pinned: true,
              delegate: StickySectionDelegate('FULL WEEK PROJECTION'),
            ),
            _FullWeekLoader(
              theoreticalBlendedWage: weekData.theoreticalBlendedWage,
              weekId: weekData.weekId,
            ),
            const SliverToBoxAdapter(child: SizedBox(height: 32)),
          ],
        ),
      ],
    );
  }
}

