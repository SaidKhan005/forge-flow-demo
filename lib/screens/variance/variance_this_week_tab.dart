    final current = _expandedDayLabel;
    if (current != null && groups.any((row) => row.dayLabel == current)) {
      return current;
    }
    return null;
  }

  void _toggleDay(String dayLabel) {
    final isCollapsing = _expandedDayLabel == dayLabel;
    setState(() {
      _expandedDayLabel = isCollapsing ? null : dayLabel;
    });
    if (isCollapsing) return;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!mounted) return;
      final rowContext = _dayRowKey(dayLabel).currentContext;
      if (rowContext == null) return;
      Scrollable.ensureVisible(
        rowContext,
        duration: const Duration(milliseconds: 250),
        curve: Curves.easeOutCubic,
        alignment: 0.0,
        alignmentPolicy: ScrollPositionAlignmentPolicy.explicit,
      );
    });
  }

  @override
  Widget build(BuildContext context) {
    // 7.55q.4-review-fix: thread the CURRENT shared
    // [ActiveTargetProfile] into the read service so day-row
    // aggregates substitute current Benchmark theoretical % for
    // non-closed children (Rule 3). Closed children continue to
    // contribute their own locked `shift.theoreticalLaborPct`
    // (Rule 4 exception). Without this Provider read the
    // `currentTargetProfile` parameter the read service grew in
    // `7.55q.4` would never receive a value in production -- only
    // the unit tests would exercise it. Honest fallback: when
    // the notifier isn't in scope (e.g. legacy widget tests),
    // the profile is null and the read service falls back to
    // per-shift values (backward-compatible).
    final currentTargetProfile = context
        .watch<ActiveTargetProfileNotifier?>()
        ?.profile;
    final projection = _readService.build(
      widget.shifts,
      currentTargetProfile: currentTargetProfile,
      servicePeriodDefinitions: _servicePeriodDefinitions,
    );
    final groups = projection.dayRows;
    if (groups.isEmpty) {
      return const SliverToBoxAdapter(child: SizedBox.shrink());
    }
    final expandedDayLabel = _resolvedExpandedDayLabel(groups);

    // Build the flat list of slivers for all days, expanded dayparts,
    // dividers, and the projected total row.
    final slivers = <Widget>[];

    for (int i = 0; i < groups.length; i++) {
      final day = groups[i];
      final isExpanded = day.dayLabel == expandedDayLabel;

      // Collapsed day header (always shown). When expanded, an orange
      // left accent stripe marks the entire day's worth of slivers.
      slivers.add(
        SliverToBoxAdapter(
          child: Container(
            margin: const EdgeInsets.symmetric(horizontal: 16),
            decoration: isExpanded
                ? const BoxDecoration(
                    border: Border(
                      left: BorderSide(color: AppColors.sunset, width: 3),
                      top: BorderSide(color: AppColors.sunset, width: 2),
                      right: BorderSide(color: AppColors.sunset, width: 2),
                    ),
                  )
                : null,
            child: _DayRow(
              key: _dayRowKey(day.dayLabel),
              row: day,
              theoreticalBlendedWage: widget.theoreticalBlendedWage,
              isExpanded: isExpanded,
              onTap: () => _toggleDay(day.dayLabel),
            ),
          ),
        ),
      );

      // Expanded daypart detail slivers
      if (isExpanded) {
        for (int j = 0; j < day.children.length; j++) {
          final dp = day.children[j];
          final isClosed = dp.status == RowStatus.closed;
          final isOpen = dp.status == RowStatus.open;
          final isLastDaypart = j == day.children.length - 1;
          final statusLabel = isClosed
              ? 'Closed'
              : isOpen
              ? 'Open'
              : 'Projected';
          final daypartLabel =
              '${dp.shift.dayLabel} ${dp.shift.daypartLabel} $statusLabel';

          // Daypart separator (between dayparts, not before the first)
          if (j > 0) {
            slivers.add(
              SliverToBoxAdapter(
                child: Container(
                  margin: const EdgeInsets.symmetric(horizontal: 16),
                  height: 12,
                  decoration: BoxDecoration(
                    border: Border(
                      left: const BorderSide(color: AppColors.sunset, width: 3),
                      right: const BorderSide(
                        color: AppColors.sunset,
                        width: 2,
                      ),
                      top: BorderSide(
                        color: AppColors.sunset.withValues(alpha: 0.6),
                        width: 1.5,
                      ),
                      bottom: BorderSide(
                        color: AppColors.sunset.withValues(alpha: 0.6),
                        width: 1.5,
                      ),
                    ),
                    gradient: LinearGradient(
                      begin: Alignment.centerLeft,
                      end: Alignment.centerRight,
                      colors: [
                        AppColors.shimmer,
                        AppColors.backgroundDeep.withValues(alpha: 0.85),
                        AppColors.shimmer,
                      ],
                    ),
                  ),
                ),
              ),
            );
          }

          // One SliverMainAxisGroup per daypart: sticky label + sticky
          // column header (closed only) + detail rows
          slivers.add(
            SliverMainAxisGroup(
              slivers: [
                SliverPersistentHeader(
                  pinned: true,
                  delegate: StickyDaypartLabelDelegate(
                    label: daypartLabel,
                    isOpen: isOpen,
                    showColumnHeaders: true,
                  ),
                ),
                SliverToBoxAdapter(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(horizontal: 16),
                    child: Container(
                      decoration: BoxDecoration(
                        gradient: const LinearGradient(
                          begin: Alignment.topCenter,
                          end: Alignment.bottomCenter,
                          colors: [AppColors.backgroundMid, AppColors.cardGlow],
                        ),
                        border: Border(
                          left: const BorderSide(
                            color: AppColors.sunset,
                            width: 3,
                          ),
                          right: const BorderSide(
                            color: AppColors.sunset,
                            width: 2,
                          ),
                          bottom: BorderSide(
                            color: isLastDaypart
                                ? AppColors.sunset
                                : AppColors.borderSubtle,
                            width: isLastDaypart ? 2 : 1,
                          ),
                        ),
                      ),
                      clipBehavior: Clip.antiAlias,
                      child: isClosed
                          ? _ClosedShiftDetail(shift: dp.shift)
                          : _ProjectedShiftDetail(
                              shift: dp.shift,
                              isOpen: isOpen,
                            ),
                    ),
                  ),
                ),
              ],
            ),
          );
        }
      }

      // Day divider between days
      if (i < groups.length - 1) {
        slivers.add(
          SliverToBoxAdapter(
            child: Container(
              margin: const EdgeInsets.symmetric(horizontal: 16),
              height: 1,
              color: AppColors.borderSubtle,
            ),
          ),
        );
      }
    }

    // Bottom border + Projected Total Row
    slivers.add(
      SliverToBoxAdapter(
        child: Container(
          margin: const EdgeInsets.symmetric(horizontal: 16),
          height: 2,
          color: AppColors.borderStrong,
        ),
      ),
    );
    slivers.add(
      SliverToBoxAdapter(
        child: Padding(
          padding: const EdgeInsets.symmetric(horizontal: 16),
          child: _ProjectedTotalRow(),
        ),
      ),
    );

    return SliverMainAxisGroup(slivers: slivers);
  }
